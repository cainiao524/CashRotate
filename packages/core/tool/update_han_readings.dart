// Regenerates presets/tool/han_readings.tsv from Unicode's Unihan database.
//
//   curl -LO https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
//   unzip Unihan.zip Unihan_Readings.txt
//   dart run tool/update_han_readings.dart path/to/Unihan_Readings.txt
//
// Keeps only the characters used by presets, so the table stays small.
// Unihan data is © Unicode, Inc., under the Unicode License v3.

import 'dart:io';

import 'package:cashrotate_core/cashrotate_core.dart';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/update_han_readings.dart Unihan_Readings.txt',
    );
    exit(2);
  }
  var root = Directory.current;
  while (!Directory('${root.path}/presets').existsSync()) {
    root = root.parent;
  }

  final used = <String>{};
  for (final f in Directory('${root.path}/presets').listSync(recursive: true)) {
    if (f is File && f.path.endsWith('.json')) {
      for (final rune in f.readAsStringSync().runes) {
        if (HanReadings.isHan(rune)) used.add(String.fromCharCode(rune));
      }
    }
  }

  final readings = <String, String>{};
  final version = <String>[];
  for (final line in File(args.single).readAsLinesSync()) {
    if (line.startsWith('# Unicode Version') || line.startsWith('# Date')) {
      version.add(line.substring(2));
    }
    final parts = line.split('\t');
    if (parts.length != 3 || parts[1] != 'kMandarin') continue;
    final ch = String.fromCharCode(int.parse(parts[0].substring(2), radix: 16));
    if (used.contains(ch)) readings[ch] = parts[2].split(' ').first;
  }

  final missing = used.difference(readings.keys.toSet());
  final sorted = readings.keys.toList()..sort();
  File('${root.path}/presets/tool/han_readings.tsv').writeAsStringSync(
    [
      '# Mandarin readings (Unihan kMandarin) for characters used in presets.',
      '# Generated by packages/core/tool/update_han_readings.dart. Do not edit.',
      '# Source: ${version.join(', ')}. © Unicode, Inc., Unicode License v3.',
      for (final ch in sorted) '$ch\t${readings[ch]}',
      '',
    ].join('\n'),
  );
  stdout.writeln('${readings.length} characters written.');
  if (missing.isNotEmpty) {
    stderr.writeln('No kMandarin reading for: ${missing.join(' ')}');
    exit(1);
  }
}
