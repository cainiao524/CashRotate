"""Renders the app icon from tool/icon_geometry.py:

- the Android vectors (adaptive foreground, themed monochrome, status bar),
- PNGs: legacy launcher sizes, the 512 px store icon and the README logo.

Run from the repository root:  python tool/render_icon.py
"""
import math
import os
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(__file__))
from icon_geometry import (ARC_R, ARC_W, ARCS, C, COIN_R, LETTER_R,  # noqa: E402
                           LETTER_W, chevron, point)

RES = 'app/android/app/src/main/res'
SS = 2048  # supersampled canvas for the 72-unit visible area
UNIT = SS / 72.0
OFFSET = 18  # the adaptive icon shows units 18..90 of 108

BG_STOPS = [(0.0, (0x1A, 0x1A, 0x1D)), (0.55, (0x2A, 0x2A, 0x2F)), (1.0, (0x1F, 0x1E, 0x23))]
PEARL = (0xF2, 0xF2, 0xF0, 255)
INK = (0x11, 0x11, 0x11, 255)


# --- vectors -------------------------------------------------------------------

def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def arc_path(start, end, r, cx=C, cy=C):
    (x0, y0), (x1, y1) = point(start, r, cx, cy), point(end, r, cx, cy)
    large = 1 if (end - start) % 360 > 180 else 0
    return f'M{f(x0)},{f(y0)} A{f(r)},{f(r)} 0 {large},1 {f(x1)},{f(y1)}'


def poly_path(pts):
    return 'M' + ' L'.join(f'{f(x)},{f(y)}' for x, y in pts)


def stroke(color, width, data, join=False):
    extra = '\n        android:strokeLineJoin="round"' if join else ''
    return f'''    <path
        android:fillColor="#00000000"
        android:strokeColor="{color}"
        android:strokeWidth="{f(width)}"
        android:strokeLineCap="round"{extra}
        android:pathData="{data}" />
'''


def circle(cx, cy, r):
    return f'M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0z'


def vector(comment, body, size=108, viewport=108):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tool/render_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}</vector>
'''


def mark_paths(color_coin, color_letter, color_arrow, outline_coin=False,
               scale=1.0, cx=C, cy=C, widths=1.0):
    def s(v):
        return v * scale

    letter = arc_path(45, 315, s(LETTER_R), cx, cy)
    body = ''
    if outline_coin:
        body += f'''    <path
        android:fillColor="#00000000"
        android:strokeColor="{color_coin}"
        android:strokeWidth="{f(s(ARC_W) * widths)}"
        android:pathData="{circle(cx, cy, s(COIN_R))}" />
'''
    else:
        body += f'''    <path
        android:fillColor="{color_coin}"
        android:pathData="{circle(cx, cy, s(COIN_R))}" />
'''
    body += stroke(color_letter, s(LETTER_W) * widths, letter)
    for start, end in ARCS:
        body += stroke(color_arrow, s(ARC_W) * widths, arc_path(start, end, s(ARC_R), cx, cy))
        body += stroke(color_arrow, s(ARC_W) * widths,
                       poly_path(chevron(end, s(ARC_R), s(5.0), cx, cy)), join=True)
    return body


def write_vectors():
    d = os.path.join(RES, 'drawable')
    with open(os.path.join(d, 'ic_launcher_foreground.xml'), 'w', encoding='utf-8') as fh:
        fh.write(vector('App icon: a pearl-white coin marked C, centred, inside two '
                        'turning arrows. Within the 66dp safe zone.',
                        mark_paths('#FFF2F2F0', '#FF111111', '#FFF2F2F0')))
    with open(os.path.join(d, 'ic_launcher_monochrome.xml'), 'w', encoding='utf-8') as fh:
        fh.write(vector('Themed (Android 13+) icon: the same mark as outlines, one colour.',
                        mark_paths('#FF000000', '#FF000000', '#FF000000', outline_coin=True)))
    with open(os.path.join(d, 'ic_stat_reminder.xml'), 'w', encoding='utf-8') as fh:
        fh.write(vector('Status-bar icon: the app mark, white on transparent.',
                        mark_paths('#FFFFFFFF', '#FFFFFFFF', '#FFFFFFFF', outline_coin=True,
                                   scale=0.36, cx=12, cy=12, widths=1.15),
                        size=24, viewport=24))


# --- PNGs ----------------------------------------------------------------------

def p(x, y):
    return ((x - OFFSET) * UNIT, (y - OFFSET) * UNIT)


def background():
    img = Image.new('RGB', (SS, SS))
    px = img.load()
    for y in range(SS):
        for x in range(SS):
            t = (x + y) / (2 * (SS - 1))
            for (a, ca), (b, cb) in zip(BG_STOPS, BG_STOPS[1:]):
                if a <= t <= b:
                    k = (t - a) / (b - a)
                    px[x, y] = tuple(round(ca[i] + (cb[i] - ca[i]) * k) for i in range(3))
                    break
    return img.convert('RGBA')


def cap(draw, x, y, w, color):
    ex, ey = p(x, y)
    draw.ellipse((ex - w / 2, ey - w / 2, ex + w / 2, ey + w / 2), fill=color)


def draw_arc(draw, r, start, end, width, color):
    w = width * UNIT
    x0, y0 = p(C - r, C - r)
    x1, y1 = p(C + r, C + r)
    pad = w / 2
    draw.arc((x0 - pad, y0 - pad, x1 + pad, y1 + pad), start, end, fill=color, width=round(w))
    for ang in (start, end):
        cap(draw, *point(ang, r), w, color)


def draw_line(draw, pts, width, color):
    w = width * UNIT
    draw.line([p(x, y) for x, y in pts], fill=color, width=round(w), joint='curve')
    for x, y in (pts[0], pts[-1]):
        cap(draw, x, y, w, color)


def mark(img):
    d = ImageDraw.Draw(img)
    x0, y0 = p(C - COIN_R, C - COIN_R)
    x1, y1 = p(C + COIN_R, C + COIN_R)
    d.ellipse((x0, y0, x1, y1), fill=PEARL)
    draw_arc(d, LETTER_R, 45, 315, LETTER_W, INK)
    for start, end in ARCS:
        draw_arc(d, ARC_R, start, end, ARC_W, PEARL)
        draw_line(d, chevron(end), ARC_W, PEARL)
    return img


def write_pngs():
    full = mark(background())
    for folder, size in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
        icon = full.resize((size, size), Image.LANCZOS)
        mask = Image.new('L', (size * 4, size * 4), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
        icon.putalpha(mask.resize((size, size), Image.LANCZOS))
        icon.save(os.path.join(RES, f'mipmap-{folder}', 'ic_launcher.png'))
    full.resize((512, 512), Image.LANCZOS).convert('RGB').save('docs/icon-512.png')
    logo = full.resize((256, 256), Image.LANCZOS)
    mask = Image.new('L', (1024, 1024), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, 1023, 1023), radius=230, fill=255)
    logo.putalpha(mask.resize((256, 256), Image.LANCZOS))
    logo.save('docs/icon.png')


if __name__ == '__main__':
    write_vectors()
    write_pngs()
